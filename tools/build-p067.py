#!/usr/bin/env python3
"""Generate the permanent P0.6.7 app; --check detects a stale release."""

from __future__ import annotations

import argparse
from html.parser import HTMLParser
from pathlib import Path
import re
import sys
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "preview-ycoor-design" / "index.html"
OUTPUT = ROOT / "crans-montana-p067" / "index.html"


def replace_once(document: str, before: str, after: str) -> str:
    if document.count(before) != 1:
        raise ValueError(f"Expected one release identity anchor: {before!r}")
    return document.replace(before, after, 1)


def render(source: str) -> str:
    document = source
    for before, after in (
        ("<title>Ycoor · Atelier DXF et façades documentées</title>", "<title>Mini Crans-Montana · P0.6.7 · Ycoor</title>"),
        ("<small>Ycoor · atelier de conception</small>", "<small>Ycoor · version P0.6.7</small>"),
        ("Aperçu · DXF et façades documentées", "DXF et façades documentées"),
        ("Ouvrir la version stable ↗", "Ouvrir la version précédente P0.6.6 ↗"),
        ("Prévisualisation distincte de la version stable : ", "P0.6.7 : "),
    ):
        document = replace_once(document, before, after)
    document = re.sub(
        r"([\"'])\./(design|assets)/",
        lambda match: f"{match[1]}../preview-ycoor-design/{match[2]}/",
        document,
    )
    return replace_once(
        document,
        "<!doctype html>",
        "<!doctype html>\n<!-- Generated by tools/build-p067.py from preview-ycoor-design/index.html; do not edit. -->",
    )


class Links(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.urls: list[str] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        for name, value in attrs:
            if name in {"src", "href"} and value:
                self.urls.append(value)


def validate(document: str) -> int:
    if re.search(r"<base\b|<iframe\b|http-equiv=[\"']refresh", document, re.I):
        raise ValueError("The release must load the app directly without a base, iframe or redirect")
    if re.search(r"[\"']\./(?:design|assets)/", document):
        raise ValueError("An unrevised preview design/assets path remains")
    links = Links()
    links.feed(document)
    links.urls.extend(re.findall(r"(?:import\(|new URL\()\s*[\"']([^\"']+)", document))
    checked = set()
    for url in links.urls:
        parsed = urlsplit(url)
        if parsed.scheme or parsed.netloc or not parsed.path or parsed.path.startswith("/"):
            continue
        path = (OUTPUT.parent / unquote(parsed.path)).resolve()
        if not path.is_relative_to(ROOT) or not path.exists():
            raise ValueError(f"Missing or invalid local release reference: {url}")
        checked.add(path)
    return len(checked)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the generated release is stale")
    args = parser.parse_args()
    document = render(SOURCE.read_text(encoding="utf-8"))
    count = validate(document)
    encoded = document.encode("utf-8")
    if args.check:
        # Git may check out CRLF on Windows; line endings do not make a release stale.
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != document:
            print("P0.6.7 is stale. Run: python tools/build-p067.py", file=sys.stderr)
            return 1
        print(f"P0.6.7 is current; {count} local references verified.")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(encoded)
    print(f"Built {OUTPUT.relative_to(ROOT).as_posix()}; {count} local references verified.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except ValueError as error:
        print(f"Cannot build P0.6.7: {error}", file=sys.stderr)
        sys.exit(1)
